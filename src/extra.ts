const pre = (n: number) => (v: string): string => (v.length <= n ? '***' : v.slice(0, n) + '***');
/** Keep the value up to and including its `count`-th `separator`, as the pack's keepThroughSeparator. */
const through = (separator: string, count: number) => (v: string): string => {
  let index = -separator.length;
  for (let n = 0; n < count; n++) {
    index = v.indexOf(separator, index + separator.length);
    if (index < 0) return '***';
  }
  return v.slice(0, index + separator.length) + '***';
};

