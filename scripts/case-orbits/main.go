// Command case-orbits writes the case-insensitive equivalence classes of FRS-1
// (SPEC §2): every Unicode simple case folding orbit with more than one member,
// with i, I, U+0130 and U+0131 merged into one class.
//
// The Java and .NET engines read this table instead of their runtime's case
// mappings, which lag behind (Java 11 ships Unicode 10) and differ between
// platforms. Regenerate it when Go moves to a new Unicode version:
//
//	go run ./scripts/case-orbits
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

var targets = []string{
	"sdk/java/core/src/main/resources/io/github/flarecollection/redact/case-orbits.txt",
	"sdk/dotnet/src/FlareRedact/Resources/case-orbits.txt",
}

func main() {
	seen := map[rune]bool{}
	var orbits [][]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if seen[r] || (r >= 0xD800 && r <= 0xDFFF) {
			continue
		}
		orbit := []rune{r}
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			orbit = append(orbit, f)
		}
		for _, x := range orbit {
			seen[x] = true
		}
		if len(orbit) > 1 {
			orbits = append(orbits, orbit)
		}
	}

	// The dotted and dotless i's: simple folding keeps U+0130 and U+0131 apart
	// from i and I; FRS-1 puts all four in one class.
	dotted := []rune{'I', 'i', 0x130, 0x131}
	kept := orbits[:0]
	for _, orbit := range orbits {
		if orbit[0] != 'I' && orbit[0] != 'i' {
			kept = append(kept, orbit)
		}
	}
	orbits = append(kept, dotted)

	for _, orbit := range orbits {
		sort.Slice(orbit, func(i, j int) bool { return orbit[i] < orbit[j] })
	}
	sort.Slice(orbits, func(i, j int) bool { return orbits[i][0] < orbits[j][0] })

	var out strings.Builder
	fmt.Fprintf(&out, "# FRS-1 case-insensitive classes: Unicode %s simple case folding orbits,\n", unicode.Version)
	out.WriteString("# with i, I, U+0130 and U+0131 merged. Generated by scripts/case-orbits; do not edit.\n")
	for _, orbit := range orbits {
		parts := make([]string, len(orbit))
		for i, r := range orbit {
			parts[i] = fmt.Sprintf("%X", r)
		}
		out.WriteString(strings.Join(parts, " "))
		out.WriteByte('\n')
	}

	for _, target := range targets {
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			fail(err)
		}
		file, err := os.Create(target)
		if err != nil {
			fail(err)
		}
		writer := bufio.NewWriter(file)
		writer.WriteString(out.String())
		if err := writer.Flush(); err != nil {
			fail(err)
		}
		file.Close()
		fmt.Printf("wrote %d classes to %s\n", len(orbits), target)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
