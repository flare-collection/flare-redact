package io.github.flarecollection.redact;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Case-insensitive equivalence for FRS-1 (SPEC §2 "Flags"): Unicode simple case
 * folding, plus i, I, İ (U+0130) and ı (U+0131) as one class.
 *
 * <p>{@code java.util.regex}'s own case-insensitive mode is not used: it compares
 * single characters and class ranges by different rules, so {@code [K]} and
 * {@code K} disagree about the Kelvin sign. Instead the translator spells every
 * case-insensitive literal and class out with the members of its class.
 *
 * <p>The classes come from a table bundled in the jar ({@code case-orbits.txt},
 * generated by {@code scripts/case-orbits}), not from the JDK's case mappings:
 * those follow the runtime's Unicode version, so the same pattern would match
 * different text on Java 11 (Unicode 10) and Java 21 (Unicode 15).
 */
final class CaseFolding {
    private CaseFolding() {
    }

    private static final class Table {
        static final Map<Integer, int[]> ORBITS = new HashMap<>();
        static final int[] MEMBERS;

        static {
            try (InputStream in = CaseFolding.class.getResourceAsStream("case-orbits.txt")) {
                if (in == null) {
                    throw new IllegalStateException("case-orbits.txt is missing from the jar");
                }
                BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.US_ASCII));
                for (String line; (line = reader.readLine()) != null; ) {
                    line = line.trim();
                    if (line.isEmpty() || line.startsWith("#")) {
                        continue;
                    }
                    String[] parts = line.split(" ");
                    int[] orbit = new int[parts.length];
                    for (int i = 0; i < parts.length; i++) {
                        orbit[i] = Integer.parseInt(parts[i], 16);
                    }
                    for (int code : orbit) {
                        ORBITS.put(code, orbit);
                    }
                }
            } catch (IOException error) {
                throw new IllegalStateException("cannot read case-orbits.txt", error);
            }
            List<Integer> keys = new ArrayList<>(ORBITS.keySet());
            int[] members = new int[keys.size()];
            for (int i = 0; i < members.length; i++) {
                members[i] = keys.get(i);
            }
            Arrays.sort(members);
            MEMBERS = members;
        }
    }

    /**
     * The class of {@code c}: every code point case-insensitively equal to it, in
     * ascending order, or null when it has none but itself.
     */
    static int[] orbit(int c) {
        return Table.ORBITS.get(c);
    }

    /** Add to {@code out} every class member of a code point in {@code [low, high]}. */
    static void closeRange(int low, int high, Set<Integer> out) {
        int[] all = Table.MEMBERS;
        int from = Arrays.binarySearch(all, low);
        if (from < 0) {
            from = -from - 1;
        }
        for (int i = from; i < all.length && all[i] <= high; i++) {
            for (int member : Table.ORBITS.get(all[i])) {
                out.add(member);
            }
        }
    }
}
