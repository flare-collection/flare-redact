using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

namespace FlareRedact
{
    /// <summary>
    /// Case-insensitive equivalence for FRS-1 (SPEC §2): Unicode simple case folding, plus
    /// i, I, İ (U+0130) and ı (U+0131) as one class.
    /// </summary>
    /// <remarks>
    /// <c>RegexOptions.IgnoreCase</c> is not used: it folds by the current culture or by a
    /// table that is not simple case folding. The translator spells every case-insensitive
    /// literal and class out with the members of its class instead. The classes come from
    /// a table embedded in the assembly (generated by <c>scripts/case-orbits</c>), so the
    /// result does not depend on the runtime's Unicode version.
    /// </remarks>
    internal static class CaseFolding
    {
        private static readonly Dictionary<int, int[]> Orbits = Load();
        private static readonly int[] Members = Sorted(Orbits.Keys);

        private static Dictionary<int, int[]> Load()
        {
            var table = new Dictionary<int, int[]>();
            using Stream? stream = typeof(CaseFolding).Assembly.GetManifestResourceStream("FlareRedact.case-orbits.txt");
            if (stream == null) throw new InvalidOperationException("case-orbits.txt is missing from the assembly");
            using var reader = new StreamReader(stream, Encoding.ASCII);
            string? line;
            while ((line = reader.ReadLine()) != null)
            {
                line = line.Trim();
                if (line.Length == 0 || line[0] == '#') continue;
                string[] parts = line.Split(' ');
                var orbit = new int[parts.Length];
                for (int i = 0; i < parts.Length; i++)
                {
                    orbit[i] = int.Parse(parts[i], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
                }
                foreach (int code in orbit) table[code] = orbit;
            }
            return table;
        }

        private static int[] Sorted(IEnumerable<int> keys)
        {
            var list = new List<int>(keys);
            list.Sort();
            return list.ToArray();
        }

        /// <summary>
        /// The class of <paramref name="code"/>: every code point case-insensitively equal to
        /// it, ascending, or null when it has none but itself.
        /// </summary>
        internal static int[]? Orbit(int code) => Orbits.TryGetValue(code, out int[]? orbit) ? orbit : null;

        /// <summary>Add every class member of a code point in [low, high] to <paramref name="output"/>.</summary>
        internal static void CloseRange(int low, int high, ISet<int> output)
        {
            int from = Array.BinarySearch(Members, low);
            if (from < 0) from = ~from;
            for (int i = from; i < Members.Length && Members[i] <= high; i++)
            {
                foreach (int member in Orbits[Members[i]]) output.Add(member);
            }
        }
    }
}
